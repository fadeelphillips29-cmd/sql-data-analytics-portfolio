DROP TABLE IF EXISTS production_log CASCADE;
DROP TABLE IF EXISTS sales_targets CASCADE;
DROP TABLE IF EXISTS order_items CASCADE;
DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS customers CASCADE;
DROP TABLE IF EXISTS employees CASCADE;

CREATE TABLE employees (
    employee_id   INTEGER PRIMARY KEY,
    first_name    VARCHAR(50)  NOT NULL,
    last_name     VARCHAR(50)  NOT NULL,
    job_title     VARCHAR(60)  NOT NULL,
    department    VARCHAR(40)  NOT NULL,
    manager_id    INTEGER REFERENCES employees (employee_id),
    hire_date     DATE         NOT NULL,
    city          VARCHAR(40)  NOT NULL,
    monthly_salary NUMERIC(10,2) NOT NULL
);

CREATE TABLE customers (
    customer_id   INTEGER PRIMARY KEY,
    company_name  VARCHAR(80)  NOT NULL,
    contact_name  VARCHAR(60)  NOT NULL,
    industry      VARCHAR(40)  NOT NULL,
    city          VARCHAR(40)  NOT NULL,
    province      VARCHAR(30)  NOT NULL,
    phone         VARCHAR(20),
    customer_since DATE        NOT NULL
);

CREATE TABLE products (
    product_id     INTEGER PRIMARY KEY,
    product_name   VARCHAR(80)  NOT NULL,
    category       VARCHAR(40)  NOT NULL,
    unit_price     NUMERIC(10,2) NOT NULL,
    unit_cost      NUMERIC(10,2) NOT NULL,
    units_in_stock INTEGER      NOT NULL,
    reorder_level  INTEGER      NOT NULL,
    discontinued   BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE orders (
    order_id      INTEGER PRIMARY KEY,
    customer_id   INTEGER NOT NULL REFERENCES customers (customer_id),
    employee_id   INTEGER NOT NULL REFERENCES employees (employee_id),
    order_date    DATE    NOT NULL,
    required_date DATE    NOT NULL,
    shipped_date  DATE,
    status        VARCHAR(20) NOT NULL,
    freight       NUMERIC(10,2) NOT NULL
);

CREATE TABLE order_items (
    order_item_id INTEGER PRIMARY KEY,
    order_id      INTEGER NOT NULL REFERENCES orders (order_id),
    product_id    INTEGER NOT NULL REFERENCES products (product_id),
    quantity      INTEGER NOT NULL CHECK (quantity > 0),
    unit_price    NUMERIC(10,2) NOT NULL,
    discount      NUMERIC(4,2)  NOT NULL DEFAULT 0
);

CREATE TABLE sales_targets (
    target_id     INTEGER PRIMARY KEY,
    employee_id   INTEGER NOT NULL REFERENCES employees (employee_id),
    target_month  DATE    NOT NULL,
    target_amount NUMERIC(12,2) NOT NULL,
    UNIQUE (employee_id, target_month)
);

CREATE TABLE production_log (
    log_id              INTEGER PRIMARY KEY,
    production_date     DATE    NOT NULL,
    line_name           VARCHAR(20) NOT NULL,
    shift               VARCHAR(10) NOT NULL,
    product_id          INTEGER NOT NULL REFERENCES products (product_id),
    planned_minutes     INTEGER NOT NULL,
    downtime_minutes    INTEGER NOT NULL,
    downtime_reason     VARCHAR(40),
    ideal_cycle_seconds INTEGER NOT NULL,
    units_produced      INTEGER NOT NULL,
    units_defective     INTEGER NOT NULL
);

